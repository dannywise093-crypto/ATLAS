import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const SEARCH_ROOTS = [".agents/skills", ".claude/skills", "agent/skills", "agents/skills"];
const OUTPUT = path.join(ROOT, "cloudflare", "generated-skill-catalog.js");
const MAX_SKILL_CHARS = 3600;

function walk(dir, found = []) {
  if (!fs.existsSync(dir)) return found;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, found);
    else if (entry.isFile() && entry.name.toLowerCase() === "skill.md") found.push(full);
  }
  return found;
}

function parseSkill(file) {
  const raw = fs.readFileSync(file, "utf8").replace(/^\uFEFF/, "");
  const match = raw.match(/^---\s*\r?\n([\s\S]*?)\r?\n---\s*\r?\n?/);
  const front = match?.[1] || "";
  const body = match ? raw.slice(match[0].length) : raw;
  const field = (name) => {
    const line = front.match(new RegExp("^" + name + ":\\s*(.*)$", "mi"));
    return line?.[1]?.trim().replace(/^["']|["']$/g, "") || "";
  };
  const list = front.match(/^\s*(?:tags|categories):\s*\[([^\]]*)\]/mi);
  const tags = list ? list[1].split(",").map((v) => v.trim().replace(/^["']|["']$/g, "")).filter(Boolean) : [];
  const name = field("name") || path.basename(path.dirname(file));
  const description = field("description") || body.split("\n").find((line) => line.trim())?.trim() || name;
  return {
    id: name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""),
    name,
    description: description.slice(0, 500),
    tags: tags.slice(0, 20),
    source: path.relative(ROOT, file).split(path.sep).join("/"),
    instructions: body.trim().slice(0, MAX_SKILL_CHARS),
  };
}

const filesFound = SEARCH_ROOTS.flatMap((root) => walk(path.join(ROOT, root)));
const byId = new Map();
for (const file of filesFound) {
  try {
    const skill = parseSkill(file);
    if (skill.id && !byId.has(skill.id)) byId.set(skill.id, skill);
  } catch (error) {
    console.warn("Skipping unreadable skill:", path.relative(ROOT, file), error.message);
  }
}
const skills = [...byId.values()].sort((a, b) => a.name.localeCompare(b.name));
const output = "// Generated by npm run skills:build. Do not edit by hand.\nexport const SKILL_CATALOG = " +
  JSON.stringify(skills, null, 2) + ";\n";
fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, output);
console.log("ATLAS skill catalog generated:", skills.length, "unique skills");
console.log("Catalog:", path.relative(ROOT, OUTPUT));
